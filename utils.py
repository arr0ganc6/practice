"""
utils.py

Вспомогательные функции проекта
"""

import os


# =====================================================
# Папки проекта
# =====================================================

PROJECT_FOLDERS = [

    "saved_models",

    "results",

    "dataset"

]


# =====================================================
# Создание папок
# =====================================================

def create_project_folders():

    for folder in PROJECT_FOLDERS:

        os.makedirs(

            folder,

            exist_ok=True

        )


# =====================================================
# Заголовок
# =====================================================

def print_header(text):

    print()

    print("=" * 70)

    print(text.center(70))

    print("=" * 70)


# =====================================================
# Успешное сообщение
# =====================================================

def print_success(text):

    print(f"[OK] {text}")


# =====================================================
# Ошибка
# =====================================================

def print_error(text):

    print(f"[ERROR] {text}")


# =====================================================
# Предупреждение
# =====================================================

def print_warning(text):

    print(f"[WARNING] {text}")


# =====================================================
# Разделитель
# =====================================================

def print_separator():

    print("-" * 70)


# =====================================================
# Проверка существования файла
# =====================================================

def file_exists(path):

    return os.path.exists(path)


# =====================================================
# Размер файла
# =====================================================

def file_size_mb(path):

    if not os.path.exists(path):

        return 0

    return round(

        os.path.getsize(path)

        / (1024 * 1024),

        2

    )


# =====================================================
# Очистка консоли
# =====================================================

def clear_console():

    os.system(

        "cls"

        if os.name == "nt"

        else "clear"

    )


# =====================================================
# Проверка
# =====================================================

if __name__ == "__main__":

    create_project_folders()

    print_header("UTILS")

    print_success("Папки проекта готовы.")

    print_separator()

    print_warning("Тестовое предупреждение.")

    print_error("Тестовая ошибка.")